"""Rule generator — génère une règle HealthCheck conforme au contrat OKA."""

import argparse
import re
import string
import sys

HITL_BANNER = """╔═══════════════════════════════════════════════════════════════╗
║  AVERTISSEMENT HITL — À VALIDER PAR L'INGÉNIEUR SUPPORT      ║
║  Le code généré est une proposition. Vérifier les 5 patterns ║
║  ci-dessous avant publication sur la plateforme OKA.          ║
╚═══════════════════════════════════════════════════════════════╝"""

PATTERNS_CHECKLIST = [
    "[ ] params_model Pydantic avec valeurs default pour tous les champs",
    "[ ] evaluate(self) -> list[Alert] (jamais None)",
    "[ ] _no_data_alert quand le provider échoue ou données vides",
    "[ ] CRITICAL vérifié avant HIGH dans _resolve_alert_level",
    "[ ] min_jobs guard si la règle scanne des jobs",
]

DEFAULT_REQUEST = "Alerter lorsque le taux d'échec des jobs dépasse 10 %"

DOMAIN_HINTS = [
    ("jobs", ["job", "échec", "echec", "failure", "timeout"]),
    ("kpi", ["coût", "cout", "cost", "kpi", "facture"]),
    ("load", ["charge", "load", "cpu", "cluster", "saturation"]),
    ("resources", ["quota", "core-hour", "core hour", "mémoire", "memoire"]),
    ("congestion", ["attente", "congestion", "queue", "file"]),
]

DOMAIN_PROVIDERS = {
    "jobs": ("self.jobs", "get_failure_rate"),
    "kpi": ("self.kpi", "get_cost_metrics"),
    "load": ("self.cluster_load", "get_cluster_load"),
    "resources": ("self.cores", "get_grouped_distribution"),
    "congestion": ("self.congestion", "get_waiting_time"),
}

RULE_TEMPLATE = '''"""Rule: $description

Generated by oka-support-desk/tools/rule_generator.py.
Domain: $domain. Provider: $provider.$method.
TODO: adapter l'appel provider et l'extraction de la métrique à la règle réelle.
"""

from pydantic import BaseModel, Field

from applications.ait.enums import ResultStatus
from applications.healthcheck.core import Alert, HealthcheckRule
from applications.healthcheck.models import AlertLevel


class Params(BaseModel):
    """Parameters for $class_name."""

    warn_pct: float = Field(
        default=$warn_pct,
        ge=0.0,
        le=1.0,
        description="Seuil HIGH (fraction de la métrique).",
    )
    critical_pct: float = Field(
        default=$critical_pct,
        ge=0.0,
        le=1.0,
        description="Seuil CRITICAL (fraction de la métrique).",
    )
    min_jobs: int = Field(
        default=1,
        ge=1,
        description="Nombre minimum de jobs avant évaluation.",
    )


class $class_name(HealthcheckRule[Params]):
    """$description"""

    params_model = Params

    def evaluate(self) -> list[Alert]:
        """Évaluer la métrique et retourner une alerte si un seuil est dépassé."""
        value, status = $provider.$method()

        if status != ResultStatus.OK or value is None:
            return [self._no_data_alert(status)]

$min_jobs_guard
        if value < self.params.warn_pct:
            return []

        level, threshold = self._resolve_alert_level(value)
        return [self._build_alert(value, level, threshold)]

    def _no_data_alert(self, status: ResultStatus) -> Alert:
        """Alerte OK informative quand le provider ne renvoie pas de données."""
        return Alert(
            level=AlertLevel.OK,
            title="No data - $rule_name",
            description=(
                f"The data provider returned status '{status.value}'; "
                "no data was available to evaluate the rule."
            ),
            reason=f"Provider returned {status.value}.",
            metadata={"status": status.value},
        )

    def _resolve_alert_level(self, value: float) -> tuple[AlertLevel, float]:
        """CRITICAL est vérifié avant HIGH."""
        if value >= self.params.critical_pct:
            return AlertLevel.CRITICAL, self.params.critical_pct
        if value >= self.params.warn_pct:
            return AlertLevel.HIGH, self.params.warn_pct
        return AlertLevel.OK, 0.0

    def _build_alert(
        self, value: float, level: AlertLevel, threshold: float
    ) -> Alert:
        """Construire l'alerte à partir de la valeur et du seuil dépassé."""
        return Alert(
            level=level,
            title=f"$description - {value:.1%}",
            description=(
                f"Value {value:.1%} exceeded the {level.label} threshold "
                f"of {threshold:.1%}."
            ),
            reason=f"Value {value:.1%} exceeded threshold {threshold:.1%}.",
            metadata={"value": round(value, 4), "threshold": round(threshold, 4)},
        )
'''


def _hitl_warning() -> None:
    print()
    print(HITL_BANNER, file=sys.stderr)
    print(file=sys.stderr)


def _detect_domain(text: str) -> str:
    lower = text.lower()
    for domain, keywords in DOMAIN_HINTS:
        if any(keyword in lower for keyword in keywords):
            return domain
    return "kpi"


def _extract_thresholds(text: str) -> tuple[float, float]:
    matches = re.findall(r"(\d+(?:[.,]\d+)?)\s*%", text)
    values = [min(0.99, max(0.0, float(match.replace(",", ".")) / 100)) for match in matches]
    if not values:
        return 0.80, 0.90
    if len(values) == 1:
        return values[0], min(0.99, values[0] + 0.10)
    return min(values), max(values)


def _sanitize(text: str, limit: int = 140) -> str:
    cleaned = " ".join(text.split())[:limit]
    return cleaned.replace('"', "'").replace("{", "(").replace("}", ")")


def analyze(request: str, domain: str | None = None, name: str | None = None) -> dict:
    description = _sanitize(request) or "Règle HealthCheck personnalisée"
    selected_domain = domain or _detect_domain(request)
    warn_pct, critical_pct = _extract_thresholds(request)
    rule_name = name or f"custom_{selected_domain}_threshold_rule"
    class_name = "".join(part.capitalize() for part in rule_name.split("_"))
    if not class_name.endswith("Rule"):
        class_name += "Rule"
    provider, method = DOMAIN_PROVIDERS.get(selected_domain, ("self.kpi", "get_metric"))
    return {
        "request": description,
        "domain": selected_domain,
        "provider": provider,
        "method": method,
        "rule_name": rule_name,
        "class_name": class_name,
        "warn_pct": warn_pct,
        "critical_pct": critical_pct,
    }


def build_rule_source(request: str, domain: str | None = None, name: str | None = None) -> str:
    info = analyze(request, domain=domain, name=name)
    if info["domain"] == "jobs":
        min_jobs_guard = (
            "        job_count = self.jobs.get_job_count()\n"
            "        if job_count < self.params.min_jobs:\n"
            "            return [self._no_data_alert(ResultStatus.OK)]"
        )
    else:
        min_jobs_guard = (
            "        # TODO: ajouter un garde-fou min_jobs si la règle scanne des jobs."
        )
    return string.Template(RULE_TEMPLATE).substitute(
        min_jobs_guard=min_jobs_guard,
        description=info["request"],
        domain=info["domain"],
        provider=info["provider"],
        method=info["method"],
        rule_name=info["rule_name"],
        class_name=info["class_name"],
        warn_pct=f"{info['warn_pct']:.2f}",
        critical_pct=f"{info['critical_pct']:.2f}",
    )


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate an OKA HealthcheckRule skeleton")
    parser.add_argument("request", nargs="*", help="Demande en langage naturel")
    parser.add_argument("--domain", choices=sorted(DOMAIN_PROVIDERS), help="Domaine OKA")
    parser.add_argument("--name", help="Nom technique de la règle")
    args = parser.parse_args()

    if args.request:
        request = " ".join(args.request)
    elif not sys.stdin.isatty():
        request = sys.stdin.read().strip() or DEFAULT_REQUEST
    else:
        request = DEFAULT_REQUEST

    _hitl_warning()
    info = analyze(request, domain=args.domain, name=args.name)

    print("Checklist des 5 patterns à vérifier avant publication :")
    print()
    for item in PATTERNS_CHECKLIST:
        print(item)
    print()
    print(f"Domaine détecté : {info['domain']} | Provider : {info['provider']}.{info['method']}")
    print(f"Inspiration : ./oka_healthchecks/{info['domain']}/ (voir NOTES_ANALYSIS.md)")
    print()
    print(build_rule_source(request, domain=args.domain, name=args.name))


if __name__ == "__main__":
    main()
